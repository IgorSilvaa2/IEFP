    private void MMActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_MMActionPerformed
        if (!Resultado.getText().isEmpty() && !Resultado.getText().equals("Erro")) {
            double Numero = Double.parseDouble(Resultado.getText());
            Numero = Numero * (-1);
            Resultado.setText(String.valueOf(Numero));
        }
    }//GEN-LAST:event_MMActionPerformed

    private void btnIgualActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIgualActionPerformed
        if (Numero1 != null && op != null && !Resultado.getText().isEmpty()) {
            Numero2 = Double.parseDouble(Resultado.getText());

            if ("+".equals(op)) {
                Resultadoigual = Numero1 + Numero2;
                Resultado.setText(String.valueOf(Resultadoigual));
            } else if ("-".equals(op)) {
                Resultadoigual = Numero1 - Numero2;
                Resultado.setText(String.valueOf(Resultadoigual));
            } else if ("*".equals(op)) {
                Resultadoigual = Numero1 * Numero2;
                Resultado.setText(String.valueOf(Resultadoigual));
            } else if ("/".equals(op)) {
                if (Numero2 == 0) {
                    Resultado.setText("Erro");
                    op = null;
                    return;
                }
                Resultadoigual = Numero1 / Numero2;
                Resultado.setText(String.valueOf(Resultadoigual));
            }
            op = null;
        }

    }//GEN-LAST:event_btnIgualActionPerformed



    private void Celsius_to_FActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Celsius_to_FActionPerformed
       try {
           double celsius = Double.parseDouble(temperatura_caixa.getText());
           double fahrenheit = (celsius * 9 /5)+ 32;
           resultado_Caixa.setText(String.format("%.2f ºF",fahrenheit));
        }catch(NumberFormatException e){
                JOptionPane.showMessageDialog(null, "Por favor, insira um número válido!", "Aviso",
                        JOptionPane.WARNING_MESSAGE);
                    temperatura_caixa.setText("");
        }
    }//GEN-LAST:event_Celsius_to_FActionPerformed


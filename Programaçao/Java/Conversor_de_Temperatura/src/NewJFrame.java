    private void Fahrenheit_to_CActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_Fahrenheit_to_CActionPerformed
        try {
           double fahrenheit = Double.parseDouble(temperatura_caixa.getText());
           double celsius = (fahrenheit - 32) * 5 / 9;;
           resultado_Caixa.setText(String.format("%.2f ºF",celsius));
        }catch(NumberFormatException e){
                JOptionPane.showMessageDialog(null, "Por favor, insira um número válido!", "Aviso",
                        JOptionPane.WARNING_MESSAGE);
                    temperatura_caixa.setText("");
        }
    }//GEN-LAST:event_Fahrenheit_to_CActionPerformed


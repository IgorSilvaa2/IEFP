    private void calcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calcularActionPerformed
        try {
            double num1 = Double.parseDouble(valor1.getText());
            double num2 = Double.parseDouble(valor2.getText());
            double total = 0;

            if (operacao.equals("+")) {
                total = num1 + num2;
            } else if (operacao.equals("-")) {
                total = num1 - num2;
            } else if (operacao.equals("*")) {
                total = num1 * num2;
            } else if (operacao.equals("/")) {
                if (num2 == 0) {
                    throw new ArithmeticException();
                }
                total = num1 / num2;
            }
            resultado.setText(String.valueOf(total));
        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Digite somente numeros");
        } catch (ArithmeticException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Não é possível dividir por zero.");
        }
    }//GEN-LAST:event_calcularActionPerformed

